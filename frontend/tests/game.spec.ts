test("design system keeps setup readable at narrow widths and enlarged text", async ({ page }) => {
  for (const width of [320, 390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto("/")
    await expect(page.getByLabel("Opponent model")).not.toHaveValue("")
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    for (const input of await page.locator("input, select").all()) {
      expect(await input.evaluate(e => parseFloat(getComputedStyle(e).fontSize))).toBeGreaterThanOrEqual(16)
      expect((await input.boundingBox())!.height).toBeGreaterThanOrEqual(44)
    }
    await page.screenshot({ path: `../artifacts/screenshots/design-setup-${width}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 320, height: 568 })
  await page.evaluate(() => document.documentElement.style.fontSize = "200%")
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.getByRole("button", { name: "Start single-player game" }).scrollIntoViewIfNeeded()
  await expect(page.getByRole("button", { name: "Start single-player game" })).toBeInViewport()
  await page.goto("/design-system/")
  await expect(page.getByRole("heading", { name: "A room for great minds." })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})

