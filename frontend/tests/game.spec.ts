test("invite fallback and clipboard both preserve the specific session", async ({ browser }) => {
  const red = await browser.newPage()
  const blue = await browser.newPage()
  await red.addInitScript(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: undefined }))
  await red.goto("http://127.0.0.1:8765")
  await red.getByLabel("Play mode").selectOption("multiplayer")
  await red.getByRole("button", { name: "Create game" }).click()
  await expect(red.getByRole("button", { name: "Join Red" })).toBeVisible()
  const session = red.url()
  expect(new URL(session).searchParams.get("game")).toBeTruthy()
  // Link is constructed from game identity, not whichever address the browser happens to display.
  await red.evaluate(() => history.replaceState(null, "", "/"))
  await red.getByRole("button", { name: "Copy invite link" }).click()
  await expect(red.getByText("Select and copy this session link:", { exact: true })).toBeVisible()
  const link = red.getByLabel("Session invite link")
  await expect(link).toHaveValue(session)
  await expect(link).toBeFocused()
  await red.screenshot({ path: "../artifacts/screenshots/09-invite-fallback.png" })
  await red.evaluate(() => Object.defineProperty(navigator, "clipboard", { configurable: true, value: {
    writeText: async (value: string) => sessionStorage.setItem("copied-invite", value),
  } }))
  await red.getByRole("button", { name: "Copy invite link" }).click()
  await expect(red.getByRole("button", { name: "Link copied" })).toBeVisible()
  expect(await red.evaluate(() => sessionStorage.getItem("copied-invite"))).toBe(session)
  await red.getByRole("button", { name: "Join Red" }).click()
  await blue.goto(session)
  await blue.getByRole("button", { name: "Join Blue" }).click()
  await expect(red.getByRole("button", { name: /^Recruit/ }).first()).toBeEnabled()
  await expect(blue.getByRole("button", { name: /^Recruit/ }).first()).toBeEnabled()
  await red.close()
  await blue.close()
})

